using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace EntityTracker.Generator;

[Generator]
public sealed class TrackingGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Invalid = new("ET001", "Invalid tracking configuration", "{0}", "EntityTracker", DiagnosticSeverity.Error, true);
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.ForAttributeWithMetadataName("EntityTracker.AspNetCore.TrackedAttribute",
            (node, _) => node is ClassDeclarationSyntax,
            (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol).Collect();
        context.RegisterSourceOutput(types.Combine(context.CompilationProvider), (ctx, input) => Generate(ctx, input.Left, input.Right));
    }
    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);
    private static string TypeName(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    private static ISymbol? Member(INamedTypeSymbol type, string name)
    {
        for (var current = type; current != null; current = current.BaseType)
        {
            var members = current.GetMembers(name).Where(x => !x.IsStatic &&
                x.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal).ToArray();
            if (members.Length != 0) return members.Length == 1 ? members[0] : null;
        }
        return null;
    }
    private static ITypeSymbol? ReturnType(ISymbol? member) => member switch
    {
        IPropertySymbol p when !p.IsIndexer && p.GetMethod != null && p.GetMethod.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal => p.Type,
        IMethodSymbol m when m.Parameters.Length == 0 && !m.IsGenericMethod && !m.ReturnsVoid => m.ReturnType,
        _ => null
    };
    private static string Access(ISymbol member) => "entity.@" + member.Name + (member is IMethodSymbol ? "()" : "");
    private static bool Supported(ITypeSymbol type) => type.SpecialType is SpecialType.System_String
        or SpecialType.System_Byte or SpecialType.System_SByte or SpecialType.System_Int16 or SpecialType.System_UInt16
        or SpecialType.System_Int32 or SpecialType.System_UInt32 or SpecialType.System_Int64 or SpecialType.System_UInt64
        || type.ToDisplayString() == "System.Guid";
    private static void Generate(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> types, Compilation compilation)
    {
        var assembly = new string((compilation.AssemblyName ?? "Application").Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n[assembly: global::EntityTracker.AspNetCore.GeneratedTrackingRegistrationAttribute(typeof(global::EntityTracker.Generated." + assembly + ".GeneratedTrackingProvider))]\nnamespace EntityTracker.Generated." + assembly + " {\n");
        var registrations = new StringBuilder();
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var type in types.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default))
        {
            void Error(string message) => context.ReportDiagnostic(Diagnostic.Create(Invalid, type.Locations.FirstOrDefault(), message));
            var attr = type.GetAttributes().First(x => x.AttributeClass?.ToDisplayString() == "EntityTracker.AspNetCore.TrackedAttribute");
            string? Setting(string key) => attr.NamedArguments.FirstOrDefault(x => x.Key == key).Value.Value as string;
            var name = Setting("Name") ?? type.Name;
            if (string.IsNullOrWhiteSpace(name) || !names.Add(name)) { Error("Tracked entity names must be nonempty and unique: " + name); continue; }
            if (type.IsGenericType || type.IsAbstract || !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            { Error("Tracked entities must be accessible, nonabstract, nongeneric classes."); continue; }
            var id = Member(type, Setting("IdMember") ?? "Id");
            var idType = ReturnType(id);
            if (id == null || idType == null || !Supported(idType) || idType.NullableAnnotation == NullableAnnotation.Annotated)
            { Error("Specify IdMember referring to an accessible property or parameterless method returning string, an integer, or Guid. Custom IDs require a string-returning member."); continue; }
            var payloadName = Setting("PayloadMember");
            var payload = payloadName == null ? null : Member(type, payloadName);
            var payloadType = ReturnType(payload);
            if (payloadName != null && (payload == null || payloadType == null))
            { Error("PayloadMember must refer to an accessible readable property or parameterless nonvoid method."); continue; }

            var entityType = TypeName(type);
            var idExpression = idType.SpecialType == SpecialType.System_String ? Access(id)
                : "global::System.Convert.ToString(" + Access(id) + ", global::System.Globalization.CultureInfo.InvariantCulture)!";
            registrations.Append("options.Add(new global::EntityTracker.AspNetCore.TrackingDescriptor(typeof(" + entityType + "), " + Literal(name)
                + ", value => { var entity = (" + entityType + ")value; return " + idExpression
                + "; }, value => { var entity = (" + entityType + ")value; return " + (payload == null ? "null" : "(object?)" + Access(payload))
                + "; }, " + (payloadType == null ? "null" : "typeof(" + TypeName(payloadType) + ")")
                + ", " + (payloadType == null || payloadType.NullableAnnotation != NullableAnnotation.NotAnnotated || (payloadType is INamedTypeSymbol named && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T) ? "true" : "false") + "));\n");
        }
        code.Append("public sealed class GeneratedTrackingProvider : global::EntityTracker.AspNetCore.IGeneratedTrackingProvider {\n"
            + "public void Register(global::EntityTracker.AspNetCore.EntityTrackerOptions options) => GeneratedTrackingRegistration.AddGeneratedTracking(options);\n"
            + "}\npublic static class GeneratedTrackingRegistration {\n"
            + "public static global::EntityTracker.AspNetCore.EntityTrackerOptions AddGeneratedTracking(this global::EntityTracker.AspNetCore.EntityTrackerOptions options) {\n"
            + "if (!options.RegisterGeneratedAssembly(typeof(GeneratedTrackingProvider).Assembly)) return options;\n"
            + registrations + "return options; }\n}\n}\n");
        context.AddSource("EntityTracking.g.cs", code.ToString());
    }
}

